CREATE TABLE documents (
    document_id VARCHAR(10) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    importance INTEGER NOT NULL,
    current_text TEXT NOT NULL,
    citizen_id VARCHAR(64)
);

CREATE TABLE citizens (
    citizen_id VARCHAR(64) PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL
);

CREATE INDEX idx_citizens_full_name ON citizens (full_name);
CREATE INDEX idx_documents_citizen_id ON documents (citizen_id);

ALTER TABLE documents
    ADD CONSTRAINT fk_render_documents_citizen
    FOREIGN KEY (citizen_id) REFERENCES citizens (citizen_id);

CREATE TABLE app_users (
    username VARCHAR(100) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    user_role VARCHAR(16) NOT NULL
);

CREATE TABLE citizen_user_access (
    username VARCHAR(100) NOT NULL,
    citizen_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (username, citizen_id),
    CONSTRAINT fk_render_user_access
        FOREIGN KEY (username) REFERENCES app_users(username),
    CONSTRAINT fk_render_citizen_access
        FOREIGN KEY (citizen_id) REFERENCES citizens(citizen_id)
);

CREATE TABLE document_versions (
    version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(10) NOT NULL,
    version_number INTEGER NOT NULL,
    text_content TEXT NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_render_document_version UNIQUE (document_id, version_number),
    CONSTRAINT fk_render_document_version
        FOREIGN KEY (document_id) REFERENCES documents(document_id)
        ON DELETE CASCADE
);

CREATE TABLE departments (
    department_id VARCHAR(64) PRIMARY KEY,
    department_name VARCHAR(150) NOT NULL UNIQUE
);

