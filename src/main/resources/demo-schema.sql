CREATE TABLE app_users (
    username VARCHAR(100) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    user_role VARCHAR(16) NOT NULL
);

CREATE TABLE citizen_user_access (
    username VARCHAR(100) NOT NULL,
    citizen_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (username, citizen_id),
    CONSTRAINT fk_demo_user_access
        FOREIGN KEY (username) REFERENCES app_users(username)
);

CREATE TABLE document_versions (
    version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(10) NOT NULL,
    version_number INT NOT NULL,
    text_content CLOB NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_demo_document_version UNIQUE (document_id, version_number),
    CONSTRAINT fk_demo_document_version
        FOREIGN KEY (document_id) REFERENCES documents(document_id)
        ON DELETE CASCADE
);

CREATE TABLE departments (
    department_id VARCHAR(64) PRIMARY KEY,
    department_name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE officers (
    officer_id VARCHAR(64) PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    department_id VARCHAR(64),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_demo_officer_user
        FOREIGN KEY (username) REFERENCES app_users(username),
    CONSTRAINT fk_demo_officer_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE document_files (
    file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(10) NOT NULL,
    stored_filename VARCHAR(36) NOT NULL UNIQUE,
    original_filename VARCHAR(255) NOT NULL,
    file_type VARCHAR(32) NOT NULL,
    file_size BIGINT NOT NULL,
    uploaded_by VARCHAR(100) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    department_id VARCHAR(64) NOT NULL,
    CONSTRAINT ck_demo_document_file_size
        CHECK (file_size > 0 AND file_size <= 10485760),
    CONSTRAINT fk_demo_document_file_document
        FOREIGN KEY (document_id) REFERENCES documents(document_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_demo_document_file_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE document_departments (
    document_id VARCHAR(10) PRIMARY KEY,
    department_id VARCHAR(64) NOT NULL,
    CONSTRAINT fk_demo_document_department_document
        FOREIGN KEY (document_id) REFERENCES documents(document_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_demo_document_department_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_username VARCHAR(100) NOT NULL,
    action_type VARCHAR(48) NOT NULL,
    target_reference VARCHAR(512),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

